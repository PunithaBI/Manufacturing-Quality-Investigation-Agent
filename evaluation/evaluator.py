from __future__ import annotations

import json
from pathlib import Path
from time import perf_counter

from app.agents.models import InvestigationRequest
from evaluation.evaluation_database import EvaluationSessionLocal
from app.db.investigation_models import (
    Investigation,
    InvestigationTraceEvent,
    InvestigationAuditRecord,
)
from app.workflow.investigation_workflow import ManufacturingInvestigationWorkflow


ROOT = Path(__file__).resolve().parent
CASES_FILE = ROOT / "cases" / "investigation_cases_v2.json"


class InvestigationEvaluator:
    def __init__(self) -> None:
        self.workflow = ManufacturingInvestigationWorkflow()
        
    def reset_evaluation_state(self) -> None:
        """
        Remove investigations generated by the evaluation suite.

        This affects only evaluation.db.
        Manufacturing source data such as NCRs, products,
        inspections, and 8D reports is preserved.
        """

        cases = self.load_cases()

        investigation_ids = [
            case.get(
                "investigation_id",
                f"EVAL-{case['case_id']}",
            )
            for case in cases
        ]

        db = EvaluationSessionLocal()

        try:
            db.query(
                InvestigationTraceEvent
            ).filter(
                InvestigationTraceEvent.investigation_id.in_(
                    investigation_ids
                )
            ).delete(
                synchronize_session=False
            )

            db.query(
                InvestigationAuditRecord
            ).filter(
                InvestigationAuditRecord.investigation_id.in_(
                    investigation_ids
                )
            ).delete(
                synchronize_session=False
            )

            db.query(
                Investigation
            ).filter(
                Investigation.investigation_id.in_(
                    investigation_ids
                )
            ).delete(
                synchronize_session=False
            )

            db.commit()

        finally:
            db.close()        

    def load_cases(self) -> list[dict]:
        with CASES_FILE.open("r", encoding="utf-8") as file:
            return json.load(file)

    def evaluate_case(self, case: dict) -> dict:
        started = perf_counter()

        investigation_id = case.get(
            "investigation_id",
            f"EVAL-{case['case_id']}",
        )

        request = InvestigationRequest(
            ncr_number=case["ncr_number"],
            investigation_id=investigation_id,
            requested_by="evaluation",
            max_results=case.get("max_results", 20),
        )

        db = EvaluationSessionLocal()

        try:
            state = self.workflow.start(
                db=db,
                request=request,
            )

            actual = {
                "workflow_started": bool(state.history),
                "final_state": state.state.value,
                "hitl_required": state.hitl_required,
                "history": state.history,
                "errors": state.errors,
            }

            passed, failures = self._evaluate_expectations(
                case["expected"],
                actual,
            )

            return {
                "case_id": case["case_id"],
                "name": case["name"],
                "passed": passed,
                "failures": failures,
                "actual": actual,
                "duration_ms": round(
                    (perf_counter() - started) * 1000,
                    2,
                ),
            }

        except Exception as exc:
            return {
                "case_id": case["case_id"],
                "name": case["name"],
                "passed": False,
                "failures": [f"Unhandled evaluator exception: {exc}"],
                "actual": {
                    "workflow_started": False,
                    "error": str(exc),
                },
                "duration_ms": round(
                    (perf_counter() - started) * 1000,
                    2,
                ),
            }

        finally:
            db.close()

    @staticmethod
    def _evaluate_expectations(
        expected: dict,
        actual: dict,
    ) -> tuple[bool, list[str]]:

        failures: list[str] = []

        if "workflow_started" in expected:
            if actual.get("workflow_started") != expected["workflow_started"]:
                failures.append(
                    "workflow_started mismatch: "
                    f"expected={expected['workflow_started']} "
                    f"actual={actual.get('workflow_started')}"
                )

        if "expected_final_state" in expected:
            if actual.get("final_state") != expected["expected_final_state"]:
                failures.append(
                    "final_state mismatch: "
                    f"expected={expected['expected_final_state']} "
                    f"actual={actual.get('final_state')}"
                )

        if "hitl_required" in expected:
            if actual.get("hitl_required") != expected["hitl_required"]:
                failures.append(
                    "hitl_required mismatch: "
                    f"expected={expected['hitl_required']} "
                    f"actual={actual.get('hitl_required')}"
                )

        return not failures, failures

    def run(self) -> dict:
        self.reset_evaluation_state()

        cases = self.load_cases()

        results = [
            self.evaluate_case(case)
            for case in cases
        ]

        passed = sum(
            1 for result in results
            if result["passed"]
        )

        failed = len(results) - passed

        total_duration = sum(
            result["duration_ms"]
            for result in results
        )

        return {
            "evaluation": {
                "total_cases": len(results),
                "passed": passed,
                "failed": failed,
                "pass_rate": (
                    round(passed / len(results), 4)
                    if results
                    else 0.0
                ),
                "total_duration_ms": round(total_duration, 2),
            },
            "cases": results,
        }
